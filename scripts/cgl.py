#!/usr/bin/env python3

from __future__ import annotations

import argparse
import html
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXAMPLES_CMAKE = ROOT / "examples" / "c" / "CMakeLists.txt"
PAGE_SCRIPT_DIR = ROOT / "site" / "page-scripts"
WEB_PAGE_TEMPLATE = ROOT / "scripts" / "templates" / "wasm-page.html"
WEB_PAGE_GENERATED_MARKER = "<!-- Generated by scripts/cgl.py; edit scripts/templates/wasm-page.html. -->"
EXAMPLE_PATTERN = re.compile(
    r"^\s*cgl_add_example\(\s*([A-Za-z0-9_.-]+)\s+([^\s)]+)([^)]*)\)",
    re.MULTILINE,
)
PLATFORM_PATTERN = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*\Z")


def example_declarations() -> list[re.Match[str]]:
    source = EXAMPLES_CMAKE.read_text(encoding="utf-8")
    return list(EXAMPLE_PATTERN.finditer(source))


def available_examples() -> list[str]:
    return [match.group(1) for match in example_declarations()]


def example_requirements(example: str) -> set[str]:
    for match in example_declarations():
        if match.group(1) == example:
            return set(match.group(3).split())
    return set()


def emscripten_toolchain() -> Path:
    candidates: list[Path] = []
    emscripten = os.environ.get("EMSCRIPTEN")
    if emscripten:
        candidates.append(
            Path(emscripten)
            / "cmake"
            / "Modules"
            / "Platform"
            / "Emscripten.cmake"
        )

    emsdk = os.environ.get("EMSDK")
    if emsdk:
        sdk_root = Path(emsdk)
        candidates.extend(
            [
                sdk_root
                / "upstream"
                / "emscripten"
                / "cmake"
                / "Modules"
                / "Platform"
                / "Emscripten.cmake",
                sdk_root / "cmake" / "Modules" / "Platform" / "Emscripten.cmake",
            ]
        )

    emcc = shutil.which("emcc")
    if emcc:
        candidates.append(
            Path(emcc).resolve().parent
            / "cmake"
            / "Modules"
            / "Platform"
            / "Emscripten.cmake"
        )

    candidates = list(dict.fromkeys(candidate.resolve() for candidate in candidates))
    for candidate in candidates:
        if candidate.is_file():
            return candidate

    message = "Could not find the Emscripten CMake toolchain."
    if emsdk:
        message += f" EMSDK is set to {Path(emsdk).resolve()}, but the toolchain file is missing."
    if not emcc:
        message += " No emcc executable was found on PATH either."
    if candidates:
        message += " Checked: " + ", ".join(str(path) for path in candidates) + "."
    message += (
        " Install and activate an SDK with `emsdk install latest` and "
        "`emsdk activate latest`, then rerun its environment setup; or pass "
        "--toolchain explicitly."
    )
    raise RuntimeError(message)


def emscripten_environment(toolchain_file: Path) -> dict[str, str]:
    environment = os.environ.copy()
    if toolchain_file.name.lower() != "emscripten.cmake":
        return environment

    emscripten_dir = toolchain_file.parents[3]
    sdk_paths = [emscripten_dir, emscripten_dir.parent / "bin"]
    existing_path = environment.get("PATH", "").split(os.pathsep)
    normalized_existing = {
        os.path.normcase(os.path.abspath(entry.strip('"')))
        for entry in existing_path
        if entry
    }
    paths_to_add = [
        str(path.resolve())
        for path in sdk_paths
        if path.is_dir()
        and os.path.normcase(os.path.abspath(str(path))) not in normalized_existing
    ]
    if paths_to_add:
        environment["PATH"] = os.pathsep.join([*paths_to_add, *existing_path])
    return environment


def add_build_options(
    parser: argparse.ArgumentParser,
    *,
    output_dir_help: str = "override the executable/assets directory",
) -> None:
    parser.add_argument(
        "--platform",
        default="native",
        help="build label (default: native); use wasm for Emscripten",
    )
    parser.add_argument(
        "--toolchain",
        type=Path,
        help="CMake toolchain file for cross-compilation",
    )
    parser.add_argument("--generator", help="CMake generator, e.g. Ninja")
    parser.add_argument("--config", default="Release", help="build configuration (default: Release)")
    parser.add_argument("--jobs", type=int, help="number of parallel build jobs")
    parser.add_argument("--build-dir", type=Path, help="override the CMake build directory")
    parser.add_argument("--output-dir", type=Path, help=output_dir_help)
    parser.add_argument(
        "--cmake-arg",
        action="append",
        default=[],
        help="extra CMake configure argument; may be repeated",
    )
    parser.add_argument(
        "--no-fetch",
        action="store_true",
        help="do not automatically fetch FreeType when an example requires it",
    )


def example_catalog_entry(example: str) -> dict[str, object] | None:
    catalog = ROOT / "site" / "db.json"
    try:
        entries = json.loads(catalog.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None

    declaration = next(
        (match for match in example_declarations() if match.group(1) == example),
        None,
    )
    source_name = Path(declaration.group(2)).name if declaration else None
    if not isinstance(entries, list):
        return None
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        source_code = entry.get("source_code", "")
        matches_example = entry.get("path") == f"builds/{example}"
        matches_source = (
            source_name is not None
            and isinstance(source_code, str)
            and source_code.endswith(f"/{source_name}")
        )
        if matches_example or matches_source:
            return entry
    return None


def example_page_metadata(example: str) -> tuple[str, str]:
    title = re.sub(r"[_-]+", " ", example).title()
    description = f"Interactive {title} example built with CGL."
    entry = example_catalog_entry(example)
    if entry:
        title = entry.get("name") or title
        description = entry.get("description") or description
    return title, description


def catalog_site_output_dir(example: str) -> Path:
    entry = example_catalog_entry(example)
    catalog_path = entry.get("path") if entry else None
    if isinstance(catalog_path, str):
        relative = Path(catalog_path)
        if relative.parts and relative.parts[0] == "builds" and ".." not in relative.parts:
            return ROOT / "site" / relative
    return ROOT / "site" / "builds" / example


def default_web_output_dir(example: str) -> Path:
    return ROOT / "build" / "examples" / "wasm" / example


def load_page_config(example: str) -> tuple[dict[str, object], str]:
    entry = example_catalog_entry(example)
    catalog_path = entry.get("path") if entry else None
    slug = Path(catalog_path).name if isinstance(catalog_path, str) else example
    config = entry.get("web_page", {}) if entry else {}
    if not isinstance(config, dict):
        raise RuntimeError(f"Catalog field 'web_page' must be an object for {example}")
    if not config:
        return {}, slug

    instructions = config.get("instructions", [])
    if not isinstance(instructions, list) or any(not isinstance(item, str) for item in instructions):
        raise RuntimeError(f"Catalog field 'web_page.instructions' must be a list of strings for {example}")

    file_actions = config.get("file_actions", [])
    if not isinstance(file_actions, list):
        raise RuntimeError(f"Catalog field 'web_page.file_actions' must be a list for {example}")
    for action in file_actions:
        if not isinstance(action, dict) or not all(
            isinstance(action.get(key), str)
            for key in ("label", "url", "virtual_path", "function")
        ):
            raise RuntimeError(
                f"Each web_page file action needs string label, url, virtual_path, and function fields for {example}"
            )
        for key in ("url", "virtual_path"):
            path = Path(action[key])
            if not action[key] or path.is_absolute() or ".." in path.parts:
                raise RuntimeError(f"Catalog field 'web_page.file_actions.{key}' must be a relative path for {example}")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", action["function"]):
            raise RuntimeError(f"Invalid C function name in web_page file action for {example}")

    script = config.get("script")
    if script is not None and (
        not isinstance(script, str)
        or Path(script).name != script
        or not script.endswith(".js")
    ):
        raise RuntimeError(f"Catalog field 'web_page.script' must be a JavaScript filename for {example}")

    return config, slug


def generate_web_page(
    example: str,
    output_dir: Path,
    *,
    force: bool = False,
) -> tuple[str, Path]:
    title, description = example_page_metadata(example)
    config, slug = load_page_config(example)
    template = WEB_PAGE_TEMPLATE.read_text(encoding="utf-8")
    config_json = (
        json.dumps(config, ensure_ascii=False)
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
    )
    script_name = config.get("script")
    script_tag = (
        '<script src="./cgl-page-custom.js"></script>' if script_name else ""
    )
    page = (
        template.replace("{{GENERATED_MARKER}}", WEB_PAGE_GENERATED_MARKER)
        .replace("{{TITLE}}", html.escape(title, quote=True))
        .replace("{{DESCRIPTION}}", html.escape(description, quote=True))
        .replace("{{PAGE_CONFIG}}", config_json)
        .replace("{{CUSTOM_SCRIPT_TAG}}", script_tag)
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    index = output_dir / "index.html"

    if index.is_file():
        current = index.read_text(encoding="utf-8")
        if WEB_PAGE_GENERATED_MARKER not in current and not force:
            return "preserved", index
        if current == page:
            return "unchanged", index
        status = "updated"
    else:
        status = "created"

    source_asset_dir = catalog_site_output_dir(example)
    for action in config.get("file_actions", []):
        relative_asset = Path(action["url"])
        source_asset = source_asset_dir / relative_asset
        output_asset = output_dir / relative_asset
        if source_asset.is_file() and source_asset.resolve() != output_asset.resolve():
            output_asset.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_asset, output_asset)

    if script_name:
        script_candidates = [PAGE_SCRIPT_DIR / f"{example}.js", PAGE_SCRIPT_DIR / f"{slug}.js"]
        source_script = next((path for path in script_candidates if path.is_file()), None)
        if source_script is None:
            raise RuntimeError(f"Page config requests missing JavaScript file: {script_name}")
        output_script = output_dir / "cgl-page-custom.js"
        if source_script.resolve() != output_script.resolve():
            shutil.copy2(source_script, output_script)

    index.write_text(page, encoding="utf-8")
    return status, index


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    arguments = list(sys.argv[1:] if argv is None else argv)
    program_args: list[str] = []

    if arguments and arguments[0] == "run" and "--" in arguments:
        separator = arguments.index("--")
        program_args = arguments[separator + 1 :]
        arguments = arguments[:separator]

    parser = argparse.ArgumentParser(
        prog="cgl",
        description="List, build, and run CGL C examples.",
        epilog=(
            "Examples:\n"
            "  python scripts/cgl.py list\n"
            "  python scripts/cgl.py build hello_cube\n"
            "  python scripts/cgl.py build-all --platform wasm\n"
            "  python scripts/cgl.py page hello_cube\n"
            "  python scripts/cgl.py run hello_cube"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    commands = parser.add_subparsers(dest="command", required=True)

    list_parser = commands.add_parser("list", help="list available C examples")
    list_parser.add_argument("filter", nargs="?", help="show names containing this text")

    page_parser = commands.add_parser(
        "page",
        help="generate a default WebAssembly launch page",
        description="Generate index.html from the shared template without building the example.",
    )
    page_parser.add_argument("example", help="example name (see `cgl list`)")
    page_parser.add_argument(
        "--output-dir",
        type=Path,
        help="page output directory (default: build/examples/wasm/<example>)",
    )
    page_parser.add_argument(
        "--force",
        action="store_true",
        help="replace an existing hand-written launch page",
    )

    build_parser = commands.add_parser("build", help="build one C example")
    build_parser.add_argument("example", help="example name (see `cgl list`)")
    add_build_options(build_parser)

    build_all_parser = commands.add_parser(
        "build-all",
        help="build every C example for a platform",
        description=(
            "Build every C example for the selected platform. When --output-dir is set, "
            "each example is placed in a child directory beneath it. The command continues "
            "after individual failures and reports them at the end."
        ),
    )
    add_build_options(
        build_all_parser,
        output_dir_help="parent output directory for per-example folders",
    )

    run_parser = commands.add_parser(
        "run",
        help="build and run a native C example",
        epilog="Pass arguments to the example after `--`, e.g. `run hello_cube -- --help`.",
    )
    run_parser.add_argument("example", help="example name (see `cgl list`)")
    add_build_options(run_parser)

    parsed = parser.parse_args(arguments)
    if parsed.command == "run":
        parsed.program_args = program_args
    elif program_args:
        parser.error("program arguments can only be passed to the run command")
    return parsed


def validate_build_args(args: argparse.Namespace, examples: list[str]) -> tuple[str, Path | None] | None:
    if args.example not in examples:
        print(f"error: unknown example {args.example!r}; use `cgl list` to see choices", file=sys.stderr)
        return None
    if not PLATFORM_PATTERN.fullmatch(args.platform) or args.platform in {".", ".."}:
        print("error: --platform must be a simple name without path separators", file=sys.stderr)
        return None
    if args.jobs is not None and args.jobs < 1:
        print("error: --jobs must be at least 1", file=sys.stderr)
        return None

    platform = args.platform.lower()
    is_wasm = platform in {"wasm", "web"}
    try:
        toolchain_file = args.toolchain.resolve() if args.toolchain else None
        if is_wasm and toolchain_file is None:
            toolchain_file = emscripten_toolchain()
        if toolchain_file is not None and not toolchain_file.is_file():
            raise RuntimeError(f"CMake toolchain file not found: {toolchain_file}")
    except RuntimeError as error:
        print(f"error: {error}", file=sys.stderr)
        return None

    return platform, toolchain_file


def build_example(args: argparse.Namespace) -> tuple[int, Path | None]:
    examples = available_examples()
    if args.example not in examples:
        print(f"error: unknown example {args.example!r}; use `cgl list` to see choices", file=sys.stderr)
        return 2, None

    validated = validate_build_args(args, examples)
    if validated is None:
        return 2, None
    platform, toolchain_file = validated
    is_wasm = platform in {"wasm", "web"}
    generator = args.generator
    if is_wasm and os.name == "nt" and generator is None:
        if not shutil.which("ninja"):
            print(
                "error: Ninja is required for Windows WebAssembly builds; install it "
                "or pass a supported generator with --generator",
                file=sys.stderr,
            )
            return 2, None
        generator = "Ninja"

    build_label = args.platform
    if is_wasm and generator:
        generator_label = re.sub(r"[^A-Za-z0-9_.-]+", "-", generator.lower()).strip("-")
        build_label = f"{args.platform}-{generator_label}"
    build_dir = (
        args.build_dir.resolve()
        if args.build_dir
        else ROOT / "build" / "examples" / ".cmake" / build_label
    )
    if args.output_dir:
        output_dir = args.output_dir.resolve()
    elif is_wasm:
        output_dir = default_web_output_dir(args.example)
    else:
        output_dir = ROOT / "build" / "examples" / args.platform / args.example

    cmake = shutil.which("cmake")
    if not cmake:
        print("error: CMake was not found on PATH", file=sys.stderr)
        return 2, None

    build_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    configure = [
        cmake,
        "-S",
        str(ROOT),
        "-B",
        str(build_dir),
        f"-DCGL_BUILD_EXAMPLE={args.example}",
        f"-DCGL_EXAMPLE_OUTPUT_DIRECTORY={output_dir}",
        f"-DCMAKE_BUILD_TYPE={args.config}",
    ]
    if "REQUIRES_FREETYPE" in example_requirements(args.example) and not args.no_fetch:
        configure.append("-DCGL_FETCH_MISSING_FREETYPE=ON")
    if is_wasm:
        configure.append("-DCGL_EXAMPLE_OUTPUT_NAME=cglweb")
    if toolchain_file:
        configure.append(f"-DCMAKE_TOOLCHAIN_FILE={toolchain_file}")
    if generator:
        configure.extend(["-G", generator])
    configure.extend(args.cmake_arg)

    build_environment = (
        emscripten_environment(toolchain_file)
        if is_wasm and toolchain_file
        else None
    )
    print(f"Building {args.example} ({args.platform}, {args.config})", flush=True)
    print(f"Build directory: {build_dir}", flush=True)
    print(f"Output directory: {output_dir}", flush=True)
    result = subprocess.run(configure, cwd=ROOT, check=False, env=build_environment)
    if result.returncode:
        return result.returncode, None

    build = [cmake, "--build", str(build_dir), "--target", args.example, "--config", args.config]
    if args.jobs:
        build.extend(["--parallel", str(args.jobs)])
    result = subprocess.run(build, cwd=ROOT, check=False, env=build_environment)
    if result.returncode:
        return result.returncode, None

    if is_wasm:
        try:
            page_status, page_path = generate_web_page(args.example, output_dir)
        except RuntimeError as error:
            print(f"error: {error}", file=sys.stderr)
            return 1, None
        print(f"Web build ready: {output_dir}", flush=True)
        if page_status == "preserved":
            print(f"Kept existing launch page: {page_path}", flush=True)
        else:
            print(f"Launch page {page_status}: {page_path}", flush=True)
        return 0, None

    executable = output_dir / f"{args.example}{'.exe' if os.name == 'nt' else ''}"
    if executable.is_file():
        print(f"Build ready: {executable}", flush=True)
        return 0, executable

    candidates = list(output_dir.rglob(f"{args.example}{'.exe' if os.name == 'nt' else ''}"))
    if candidates:
        executable = candidates[0]
        print(f"Build ready: {executable}", flush=True)
        return 0, executable

    print(f"error: build succeeded but executable was not found under {output_dir}", file=sys.stderr)
    return 1, None


def build_all_examples(args: argparse.Namespace) -> int:
    examples = available_examples()
    if not examples:
        print("error: no C examples are registered", file=sys.stderr)
        return 2

    preflight_args = argparse.Namespace(**vars(args))
    preflight_args.example = examples[0]
    if validate_build_args(preflight_args, examples) is None:
        return 2
    if not shutil.which("cmake"):
        print("error: CMake was not found on PATH", file=sys.stderr)
        return 2
    if (
        args.platform.lower() in {"wasm", "web"}
        and os.name == "nt"
        and args.generator is None
        and not shutil.which("ninja")
    ):
        print(
            "error: Ninja is required for Windows WebAssembly builds; install it "
            "or pass a supported generator with --generator",
            file=sys.stderr,
        )
        return 2

    failures: list[str] = []
    output_root = args.output_dir

    for example in examples:
        example_args = argparse.Namespace(**vars(args))
        example_args.example = example
        if output_root is not None:
            example_args.output_dir = output_root / example

        result, _ = build_example(example_args)
        if result:
            failures.append(example)

    if failures:
        print(
            f"Build-all finished with {len(failures)} failure(s): {', '.join(failures)}",
            file=sys.stderr,
        )
        return 1

    print(f"Built all {len(examples)} examples for {args.platform}.")
    return 0


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.command == "list":
        examples = available_examples()
        if args.filter:
            examples = [name for name in examples if args.filter.casefold() in name.casefold()]
        if examples:
            print("\n".join(examples))
        else:
            print("No matching examples.")
        return 0

    if args.command == "build-all":
        return build_all_examples(args)

    if args.command == "page":
        if args.example not in available_examples():
            print(f"error: unknown example {args.example!r}; use `cgl list` to see choices", file=sys.stderr)
            return 2
        output_dir = args.output_dir.resolve() if args.output_dir else default_web_output_dir(args.example)
        try:
            page_status, page_path = generate_web_page(
                args.example,
                output_dir,
                force=args.force,
            )
        except RuntimeError as error:
            print(f"error: {error}", file=sys.stderr)
            return 2
        if page_status == "preserved":
            print(f"Kept existing launch page: {page_path}")
        else:
            print(f"Launch page {page_status}: {page_path}")
        return 0

    if args.command == "run":
        if args.platform.lower() != "native" or args.toolchain:
            print("error: `run` supports native host builds only", file=sys.stderr)
            return 2

    result, executable = build_example(args)
    if result or args.command == "build":
        return result
    if executable is None:
        print("error: this build does not produce a native executable", file=sys.stderr)
        return 2

    print(f"Running: {executable}\n", flush=True)
    return subprocess.run([str(executable), *args.program_args], cwd=ROOT, check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
